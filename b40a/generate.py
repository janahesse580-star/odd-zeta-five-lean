#!/usr/bin/env python3
"""Generate kernel-checked shards from B40a's unchanged JSON certificate."""
import argparse
import json
from fractions import Fraction
from math import ceil, floor
from pathlib import Path

PREFIX = "OddZetaSix.B40a.Certificate"
NAMESPACE = "OddZetaSix.B40a.Cert"
FIX = 10**9
COORD = 10**6
BINS = 128
PEAK = -8443338478


def atanh_log(x):
    z = (x-1)/(x+1)
    terms = [2*FIX*z**(2*j+1)/(2*j+1) for j in range(18)]
    tail = 2*FIX*z**37/(37*(1-z*z))
    return sum(map(floor, terms)), sum(map(ceil, terms)) + ceil(tail)


def log_tables():
    two = atanh_log(Fraction(2))
    exponent = COORD.bit_length()-1
    res = atanh_log(Fraction(COORD, 2**exponent))
    ln_coord = tuple(exponent*a + b for a,b in zip(two,res))
    nodes = [atanh_log(Fraction(BINS+i,BINS)) for i in range(BINS+1)]
    shifts = [(i*two[0]-2*ln_coord[1],i*two[1]-2*ln_coord[0]) for i in range(80)]
    return nodes, shifts


def lower_energy(circles, table):
    nodes, shifts = table

    def log_lower(d):
        exponent = d.bit_length()-1
        base = 2**exponent
        k, rem = divmod(d*BINS,base)
        return nodes[k-BINS][0]+shifts[exponent][0]+(FIX*rem)//((k+1)*base)

    def row(i):
        x,y,r,m = circles[i]
        total = 0
        for j,(u,v,_,n) in enumerate(circles):
            same = r*r if i==j else (x-u)**2+(y-v)**2
            opp = (x-u)**2+(y+v)**2
            total += m*n*(log_lower(same*10**6)+log_lower(opp*10**6))
        return total

    return [row(i) for i in range(len(circles))]


def integer(n):
    return f"({n})" if n<0 else str(n)


def rational(text):
    v = Fraction(text)
    return f"qfrac {integer(v.numerator)} {v.denominator}"


def literal(rows, encode):
    return "[\n  " + ",\n  ".join(map(encode, rows)) + "\n]"


def generate(data, dest, size):
    if data["model"]!="B40a-v1":
        raise ValueError("wrong model")
    geom, arith = data["analytic"], data["arithmetic"]
    if (len(geom["circles"]),len(geom["panels"])-1,len(arith["small_period"]),len(arith["middle"]))!=(34,119,706,1375):
        raise ValueError("wrong certificate shape")
    dest.mkdir(parents=True,exist_ok=True)
    table=log_tables()
    energy=lower_energy(geom["circles"],table)
    imports=[]

    def write(name, body, deps):
        text="\n".join("import "+d for d in deps)
        text+="\n\n-- Generated by b40a/generate.py.\nnamespace "+NAMESPACE+"\n"
        text+="\nset_option maxHeartbeats 0\nset_option maxRecDepth 16384\n\n"
        text+=body+"\n\nend "+NAMESPACE+"\n"
        (dest/f"{name}.lean").write_text(text,encoding="utf-8")
        imports.append(f"{PREFIX}.Generated.{name}")

    circles=literal(geom["circles"],lambda row: "⟨"+", ".join(map(integer,row))+"⟩")
    nodes, shifts=map(lambda x: "#"+literal(x,lambda row: "⟨"+", ".join(map(integer,row))+"⟩"),table)
    lookup = f"def lookup : Lookup := ⟨{nodes}, {shifts}⟩\n"
    rows=literal(list(zip(geom["circles"],energy)),lambda pair: "(⟨"+", ".join(map(integer,pair[0]))+f"⟩,{integer(pair[1])})")
    write("Witness", lookup+f"def circles : List Circle := {circles}\n"+
          f"def energyRows : List (Circle × Int) := {rows}\n"+
          f"def peak : Int := {PEAK}\n"+
          "theorem circles_ok : circles.length = 34 ∧ circles.all circleOK = true ∧\n"
          "    (circles.map Circle.mass).sum = massTotal ∧\n"
          "    ((circles.map fun c => (c.re,c.im)).eraseDups).length = 34 := by decide +kernel\n"
          "theorem energies_cover : energyRows.map (fun r => (r.1.re,r.1.im,r.1.radius,r.1.mass)) =\n"
          "    circles.map (fun c => (c.re,c.im,c.radius,c.mass)) := by decide +kernel\n"
          "",
          [f"{PREFIX}.Analytic"])

    groups={"middle":arith["middle"],"small":arith["small_period"],
            "panels":list(zip(geom["panels"],geom["panels"][1:]))}
    index={}
    checks={}
    for group, rows in groups.items():
        index[group]=[]
        checks[group]=[]
        for i in range(0,len(rows),size):
            name=f"{group}{i//size:03}"
            typ="Panel" if group=="panels" else "ArithRow"
            if group=="panels":
                data=literal(rows[i:i+size],lambda p: f"⟨{p[0]}, {p[1]}⟩")
                pred="checkPanel lookup circles peak"
                module=f"{PREFIX}.Generated.Witness"
            else:
                data=literal(rows[i:i+size],lambda r: f"⟨{rational(r[0])}, {rational(r[1])}, {integer(r[2])}⟩")
                pred="checkArithRow "+str(group=="small").lower()
                module=f"{PREFIX}.Arithmetic"
            chunk_content = f"def {name} : List {typ} := {data}\n"
            if group=="small":
                chunk_content += f"theorem {name}_ok : {name}.all ({pred}) = true := by decide +kernel"
            write(name.capitalize(),chunk_content,[module])
            index[group].append(name)
            checks[group].append(f"{name}_ok")

    all_checks = imports.copy()
    joined=[]
    for group, names in index.items():
        typ="Panel" if group=="panels" else "ArithRow"
        check="checkPanel lookup circles peak" if group=="panels" else "checkArithRow "+str(group=="small").lower()
        joined.append(f"def {group}Rows : List {typ} := " + " ++ ".join(names))
        if group=="small":
            joined.append(f"theorem {group}Rows_ok : {group}Rows.all ({check}) = true := by\n"
                          f"  simp only [{group}Rows, List.all_append, {', '.join(checks[group])}, Bool.true_and]")
    joined.extend([
        "def energySum : Int := (energyRows.map Prod.snd).sum",
        "def aCert : ℚ := numericalA peak energySum",
        "def cCert : ℚ := qfrac (arithTotal middleRows + arithTotal smallRows) 1000000000000 + highTail",
        "theorem highTail_ok : highTail = 1671/2000 := by decide +kernel",
        "theorem middle_chain : arithChain (11/20) 50 middleRows = true := by decide +kernel",
        "theorem small_chain : arithChain 0 1 smallRows = true := by decide +kernel",
        "theorem panel_chain : panelChain 0 400000 panelsRows = true := by decide +kernel",
        "theorem numericA_ok : aCert ≤ -619/100 := by decide +kernel",
        "theorem numericC_ok : cCert ≤ 61405/10000 := by decide +kernel",
        "theorem numeric_net : aCert+cCert ≤ -495/10000 ∧ (-495/10000 : ℚ) < 0 := by decide +kernel",
    ])
    write("All", "\n\n".join(joined),all_checks)


if __name__=="__main__":
    directory=Path(__file__).resolve().parent
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--certificate",type=Path,default=directory/"certificate.json")
    parser.add_argument("--output",type=Path,default=directory.parent/Path(*PREFIX.split("."))/"Generated")
    parser.add_argument("--chunk",type=int,choices=(32,64),default=32)
    args=parser.parse_args()
    generate(json.loads(args.certificate.read_text()),args.output,args.chunk)
