#!/usr/bin/env python3
"""Pick a folding cut for each unmodified middle row and emit Lean checks."""

import argparse
from fractions import Fraction
import json
from pathlib import Path
import runpy


ROOT = Path(__file__).resolve().parents[1]
PREFIX = "OddZetaSix.B40a.Certificate"
NAMESPACE = "OddZetaSix.B40a.Cert"
UNIT = 10**12
ROWS_PER_SHARD = 32


def capped(d, histogram):
    cumulative = total = 0
    for k in range(16, 0, -1):
        cumulative += histogram[k]
        total += min(40 * d, cumulative)
    return total


def best_cut(left, right, upper, slot_weights):
    m = (left + right) / 2
    p, d = 4 * m.numerator, 4 * m.denominator
    residues = [(r * d) % p for r in (16, 17, 25, 34, 59)]
    walls = sorted({0, p // 2, *(min(r, p - r) for r in residues)})
    classes = []
    for lo, hi in zip(walls, walls[1:]):
        start = (lo + hi) // 2
        bag = sorted(
            (w for a in (start, p - start) for t in range(a, 25 * d, p)
             for w in slot_weights(p, d, t) if 1 <= w <= 16),
            reverse=True,
        )
        classes.append((hi - lo, bag))

    unfolded = [0] * 17
    for width, bag in classes:
        for w in bag:
            unfolded[w] += width
    cut = None
    best = capped(d, unfolded)
    prior = [0] * 17
    limit = 80 * d // p
    for q in range(limit + 1):
        for width, bag in classes:
            if q < len(bag):
                prior[bag[q]] += width
        histogram = prior.copy()
        for width, bag in classes:
            for rank in range(q + 1, min(q + 8, len(bag))):
                w = bag[rank] - 2 * (rank - q)
                if w > 0:
                    histogram[w] += width
        charge = 80 * d * (limit - q) - p * ((limit + q + 1) * (limit - q) // 2)
        cost = charge + capped(d, histogram)
        if cost < best:
            cut, best = q, cost
    if (right - left) * best * UNIT > upper * 2000 * d:
        raise ValueError(f"selected cut exceeds the existing bound on [{left}, {right}]")
    return cut


def source(imports, body):
    return (
        "".join(f"import {module}\n" for module in imports)
        + f"\n-- Generated by b40a/generate-middle-witnesses.py.\nnamespace {NAMESPACE}\n\n"
        + body + f"\nend {NAMESPACE}\n"
    )


def write_shard(path, text):
    encoded = text.encode("utf-8")
    if not path.exists() or path.read_bytes() != encoded:
        path.write_bytes(encoded)


def generate(output):
    certificate = json.loads((ROOT / "b40a/certificate.json").read_text(encoding="utf-8"))
    rows = certificate["arithmetic"]["middle"]
    if len(rows) != 1375:
        raise ValueError("unexpected middle certificate length")
    slot_weights = runpy.run_path(str(ROOT / "verify-certificate.py"))["slot_weights"]
    output.mkdir(parents=True, exist_ok=True)
    names = []
    for start in range(0, len(rows), ROWS_PER_SHARD):
        name = f"Middle{start // ROWS_PER_SHARD:03}"
        cuts = [best_cut(Fraction(a), Fraction(b), u, slot_weights)
                for a, b, u in rows[start:start + ROWS_PER_SHARD]]
        literals = ["none" if q is None else f"some {q}" for q in cuts]
        wrapped = ",\n  ".join(", ".join(literals[i:i + 8]) for i in range(0, len(literals), 8))
        body = (
            "set_option maxHeartbeats 0\nset_option maxRecDepth 16384\n\n"
            f"def qWitness{name} : List (Option ℕ) := [\n  {wrapped}]\n\n"
            f"theorem {name[0].lower() + name[1:]}_fast_checked :\n"
            f"    checkFastMiddle {name[0].lower() + name[1:]} qWitness{name} = true := by\n"
            "  decide +kernel\n"
        )
        imports = [f"{PREFIX}.FastMiddle", f"{PREFIX}.Generated.{name}"]
        write_shard(output / f"{name}.lean", source(imports, body))
        names.append(name)

    imports = [f"{PREFIX}.FastMiddleSound", *(f"{PREFIX}.FastGenerated.{n}" for n in names)]
    cuts = " ++\n  ".join(f"qWitness{n}" for n in names)
    checks = [f"{n.lower()}_fast_checked" for n in names]
    chain = [f"  have checked0 := {checks[0]}"]
    for i, name in enumerate(checks[1:], 1):
        chain.append(f"  have checked{i} := checkFastMiddle_append checked{i-1} {name}")
    chain.append(f"  exact checked{len(checks)-1}")
    body = (
        "set_option maxHeartbeats 0\nset_option maxRecDepth 16384\n\n"
        f"def middleQWitnesses : List (Option ℕ) :=\n  {cuts}\n\n"
        "theorem fast_middle_rows_checked : checkFastMiddle middleRows middleQWitnesses = true := by\n"
        "  unfold middleRows middleQWitnesses\n"
        + "\n".join(chain) + "\n\n"
        "theorem fast_middle_rows_sum_bound :\n"
        "    (middleRows.map (rowValue false)).sum ≤ (arithTotal middleRows : ℚ)/bigUnit :=\n"
        "  checkedFastMiddle_sum_bound _ _ fast_middle_rows_checked\n"
    )
    write_shard(output / "All.lean", source(imports, body))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path,
                        default=ROOT / "OddZetaSix/B40a/Certificate/FastGenerated")
    generate(parser.parse_args().output)
